def build_kpoints(cell: Cell, settings: Optional[Dict] = None) -> str:
    settings = {**default_settings(), **(settings or {})}
    mode = settings.get("kpoint_mode", KPOINT_MODES[1])

    if mode == "Gamma-only":
        mesh, shift, centring = (1, 1, 1), (0.0, 0.0, 0.0), "Gamma"
    elif mode == "Automatic (spacing)":
        mesh = kpoint_mesh_from_density(cell, float(settings.get("kspacing", 0.03)))
        shift, centring = (0.0, 0.0, 0.0), "Gamma"
    else:
        mesh = tuple(max(1, int(value)) for value in settings.get("kmesh", [4, 4, 4]))
        shift = tuple(float(value) for value in settings.get("kshift", [0.0, 0.0, 0.0]))
        centring = "Monkhorst-Pack" if mode.startswith("Monkhorst") else "Gamma"

    header = f"Automatic mesh ({mode})"
    return (
        f"{header}\n0\n{centring}\n"
        f"  {mesh[0]:d}  {mesh[1]:d}  {mesh[2]:d}\n"
        f"  {shift[0]:g}  {shift[1]:g}  {shift[2]:g}\n"
    )


