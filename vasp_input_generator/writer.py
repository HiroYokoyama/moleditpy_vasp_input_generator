def build_poscar(cell: Cell, settings: Optional[Dict] = None) -> str:
    settings = {**default_settings(), **(settings or {})}
    atoms, counts = sorted_by_species(cell)

    lines: List[str] = []
    title = str(settings.get("title") or cell.name).strip() or "POSCAR"
    lines.append(title.replace("\n", " "))
    lines.append("   1.00000000000000")
    for vector in cell.lattice:
        lines.append(
            "  {: >21.16f} {: >21.16f} {: >21.16f}".format(*[float(v) for v in vector])
        )
    lines.append("  " + "  ".join(f"{element:>4}" for element, _ in counts))
    lines.append("  " + "  ".join(f"{count:>4d}" for _, count in counts))

    selective = bool(settings.get("selective_dynamics"))
    frozen = set(int(index) for index in settings.get("frozen_indices") or [])
    if selective:
        lines.append("Selective dynamics")

    cartesian = settings.get("coord_mode") == COORD_MODES[1]
    lines.append("Cartesian" if cartesian else "Direct")

    # frozen_indices refer to the *original* cell ordering, so map through the
    # species sort rather than using the emitted row number.
    order = []
    for _, indices in _species_indices(cell):
        order.extend(indices)

    for row, atom in enumerate(atoms):
        values = atom.cart if cartesian else atom.fract
        line = "  {: >19.16f} {: >19.16f} {: >19.16f}".format(*[float(v) for v in values])
        if selective:
            flag = "F   F   F" if order[row] in frozen else "T   T   T"
            line += f"   {flag}"
        line += f"   ! {atom.label}"
        lines.append(line)

    return "\n".join(lines) + "\n"


def _species_indices(cell: Cell):
    from .cell_model import group_by_species

    return group_by_species(cell)


