def _task_tags(settings: Dict) -> List[tuple]:
    task = settings.get("task", TASKS[0])
    nsw = int(settings.get("nsw", 100))
    tags: List[tuple] = []

    if task == "Single point (SCF)":
        tags += [("IBRION", -1), ("NSW", 0)]
    elif task == "Relax ions":
        tags += [("IBRION", 2), ("ISIF", 2), ("NSW", nsw), ("EDIFFG", settings.get("ediffg", -0.02))]
    elif task == "Relax ions + cell":
        tags += [("IBRION", 2), ("ISIF", 3), ("NSW", nsw), ("EDIFFG", settings.get("ediffg", -0.02))]
    elif task == "Density of states":
        tags += [("IBRION", -1), ("NSW", 0), ("LORBIT", 11), ("NEDOS", 3001)]
    elif task == "Band structure (non-SCF)":
        tags += [("IBRION", -1), ("NSW", 0), ("ICHARG", 11), ("LORBIT", 11)]
    elif task == "Molecular dynamics (NVT)":
        tags += [
            ("IBRION", 0),
            ("MDALGO", 2),
            ("SMASS", 0),
            ("NSW", max(1, nsw)),
            ("POTIM", settings.get("potim", 1.0)),
            ("TEBEG", settings.get("temperature", 300.0)),
            ("TEEND", settings.get("temperature", 300.0)),
        ]
    return tags


def _functional_tags(settings: Dict) -> List[tuple]:
    functional = settings.get("functional", FUNCTIONALS[0])
    if functional.startswith("PBE ("):
        return []  # PBE POTCARs already carry GGA = PE
    if functional.startswith("PBEsol") or functional.startswith("PS"):
        return [("GGA", "PS")]
    if functional.startswith("RPBE"):
        return [("GGA", "RP")]
    if functional.startswith("LDA"):
        return [("GGA", "CA")]
    return []


def _vdw_tags(settings: Dict) -> List[tuple]:
    mapping = {
        "DFT-D2 (IVDW=1)": 1,
        "TS (IVDW=2)": 2,
        "DFT-D3 (IVDW=11)": 11,
        "DFT-D3(BJ) (IVDW=12)": 12,
    }
    value = mapping.get(settings.get("vdw", "None"))
    return [("IVDW", value)] if value else []


def _smearing_tags(settings: Dict) -> List[tuple]:
    task = settings.get("task")
    label = settings.get("smearing", SMEARING[0])
    ismear = {
        "Gaussian (ISMEAR=0)": 0,
        "Methfessel-Paxton 1 (ISMEAR=1)": 1,
        "Fermi (ISMEAR=-1)": -1,
        "Tetrahedron + Blochl (ISMEAR=-5)": -5,
    }.get(label, 0)
    if task == "Density of states" and ismear >= 0:
        ismear = -5  # tetrahedron gives a far smoother DOS
    tags = [("ISMEAR", ismear)]
    if ismear >= -1:
        tags.append(("SIGMA", settings.get("sigma", 0.05)))
    return tags


def build_incar(settings: Optional[Dict] = None, counts: Optional[Sequence] = None) -> str:
    settings = {**default_settings(), **(settings or {})}

    tags: List[tuple] = [
        ("SYSTEM", str(settings.get("title") or "MoleditPy").replace("\n", " ")),
        ("PREC", settings.get("prec", "Accurate")),
        ("ENCUT", settings.get("encut", 520.0)),
        ("EDIFF", settings.get("ediff", 1e-6)),
        ("ALGO", settings.get("algo", "Normal")),
        ("NELM", int(settings.get("nelm", 120))),
        ("LREAL", settings.get("lreal", "Auto")),
        ("ISYM", int(settings.get("isym", 2))),
    ]
    tags += _functional_tags(settings)
    tags += _smearing_tags(settings)
    tags += _task_tags(settings)

    if settings.get("ispin"):
        tags.append(("ISPIN", 2))
        if settings.get("magmom_auto") and counts:
            tags.append(("MAGMOM", potentials.magmom_defaults(counts)))

    tags += _vdw_tags(settings)
    tags.append(("LWAVE", ".TRUE." if settings.get("lwave") else ".FALSE."))
    tags.append(("LCHARG", ".TRUE." if settings.get("lcharg") else ".FALSE."))
    ncore = int(settings.get("ncore", 0) or 0)
    if ncore > 1:
        tags.append(("NCORE", ncore))

    lines = [f"{key:<8}= {_format_value(value)}" for key, value in tags]

    extra = str(settings.get("extra_incar") or "").strip()
    if extra:
        lines.append("")
        lines.append("! --- additional tags ---")
        lines.extend(extra.splitlines())

    return "\n".join(lines) + "\n"


def _format_value(value) -> str:
    if isinstance(value, bool):
        return ".TRUE." if value else ".FALSE."
    if isinstance(value, float):
        if value != 0 and (abs(value) < 1e-3 or abs(value) >= 1e5):
            return f"{value:.1E}"
        return f"{value:g}"
    return str(value)


