def build_potcar_notes(cell: Cell, settings: Optional[Dict] = None) -> str:
    settings = {**default_settings(), **(settings or {})}
    _, counts = sorted_by_species(cell)
    elements = [element for element, _ in counts]
    recommended = bool(settings.get("recommended_potcar", True))
    names = potentials.potcar_names(elements, recommended)

    lines = [
        "# POTCAR is licensed VASP data and cannot be generated here.",
        "# Concatenate the files in the SAME element order as POSCAR:",
        "#",
        f"#   {'  '.join(elements)}",
        "#",
        potentials.concat_command(names),
    ]
    missing = potentials.unmapped_elements(elements)
    if missing and recommended:
        lines.append(
            "# No recommended-set entry for: "
            + ", ".join(missing)
            + " (plain symbol used)."
        )
    return "\n".join(lines) + "\n"


def build_all(cell: Cell, settings: Optional[Dict] = None) -> Dict[str, str]:
    settings = {**default_settings(), **(settings or {})}
    _, counts = sorted_by_species(cell)
    return {
        "POSCAR": build_poscar(cell, settings),
        "INCAR": build_incar(settings, counts),
        "KPOINTS": build_kpoints(cell, settings),
        "POTCAR.readme": build_potcar_notes(cell, settings),
    }


def build_preview(cell: Cell, settings: Optional[Dict] = None) -> str:
    files = build_all(cell, settings)
    chunks = []
    for name in ("INCAR", "KPOINTS", "POSCAR", "POTCAR.readme"):
        chunks.append(f"{'=' * 28} {name} {'=' * 28}\n{files[name]}")
    return "\n".join(chunks)


